#!/usr/bin/env python3
"""Generate the frozen C++ command identifiers from the Rust catalogue.

The single source of truth is pictura_script::command_catalogue::const_names().
The generated header is checked in so 1026 C++ call sites keep compile-time
constants; run this script after changing the Rust table.

Usage:
    scripts/gen-command-ids.py             # regenerate command_ids.h
    scripts/gen-command-ids.py --check     # fail when the header is stale
    scripts/gen-command-ids.py --source crates/pictura-app/cpp/commands.h
                                           # bootstrap from the old inline list

The Rust parser accepts either a dedicated const-names file or the catalogue
module: it scans files under the source directory for the const_names table and
reads every ("Name", "value") pair after that marker. The header parser reads
the previous inline `inline constexpr char Name[] = "value";` form.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_SOURCE = ROOT / "crates" / "pictura-script" / "src"
DEFAULT_OUTPUT = ROOT / "crates" / "pictura-app" / "cpp" / "command_ids.h"

HEADER_PAIR = re.compile(r'inline\s+constexpr\s+char\s+(\w+)\[\]\s*=\s*"([^"]*)";')
RUST_PAIR = re.compile(r'\(\s*"([A-Za-z_]\w*)"\s*,\s*"([^"]*)"\s*\)')


def parse_header(path: Path) -> list[tuple[str, str]]:
    return HEADER_PAIR.findall(path.read_text(encoding="utf-8"))


def parse_rust(path: Path) -> list[tuple[str, str]]:
    text = path.read_text(encoding="utf-8")
    marker = text.find("const_names")
    if marker < 0:
        marker = text.find("CONST_NAMES")
    if marker < 0:
        return []
    position = marker
    while True:
        start = text.find("[", position)
        if start < 0:
            return []
        depth = 0
        end = len(text)
        for index in range(start, len(text)):
            char = text[index]
            if char == "[":
                depth += 1
            elif char == "]":
                depth -= 1
                if depth == 0:
                    end = index
                    break
        pairs = RUST_PAIR.findall(text[start : end + 1])
        if pairs:
            return pairs
        position = end + 1


def read_pairs(source: Path) -> list[tuple[str, str]]:
    if source.is_file() and source.suffix in {".h", ".hpp", ".hh"}:
        pairs = parse_header(source)
    else:
        files = [source] if source.is_file() else sorted(source.rglob("*.rs"))
        pairs = []
        for path in files:
            pairs.extend(parse_rust(path))
        if not pairs and not source.exists():
            raise SystemExit(f"source not found: {source}")
    if not pairs:
        raise SystemExit(f"no command identifiers found in {source}")
    seen_names: dict[str, str] = {}
    seen_values: dict[str, str] = {}
    for name, value in pairs:
        if name in seen_names:
            raise SystemExit(f"duplicate identifier name: {name}")
        if value in seen_values:
            raise SystemExit(
                f"duplicate identifier value: {value} ({seen_values[value]}, {name})"
            )
        seen_names[name] = value
        seen_values[value] = name
    return pairs


def render(pairs: list[tuple[str, str]]) -> str:
    lines = [
        "// Generated by scripts/gen-command-ids.py from",
        "// pictura_script::command_catalogue::const_names(); do not edit by hand.",
        "#pragma once",
        "",
        "namespace pictura::command_ids {",
    ]
    lines.extend(f'inline constexpr char {name}[] = "{value}";' for name, value in pairs)
    lines.extend(["} // namespace pictura::command_ids", ""])
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, default=DEFAULT_SOURCE)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()

    pairs = read_pairs(args.source)
    generated = render(pairs)
    if args.check:
        if not args.output.exists():
            print(f"drift: {args.output} is missing", file=sys.stderr)
            return 1
        if args.output.read_text(encoding="utf-8") != generated:
            print(
                f"drift: {args.output} does not match {len(pairs)} catalogue entries; "
                "run scripts/gen-command-ids.py",
                file=sys.stderr,
            )
            return 1
        print(f"{len(pairs)} command identifiers match {args.output}")
        return 0
    args.output.write_text(generated, encoding="utf-8")
    print(f"wrote {len(pairs)} command identifiers to {args.output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
