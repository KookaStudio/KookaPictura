#!/usr/bin/env python3
"""Generate design-system.html from the app's theme token dump.

Runs `./build/pictura --headless --dump-theme`, emits the token JSON as CSS
custom properties (one block per brightness level), and writes
`design-system.html` at the repository root. The script is the drift guard for
the token contract: run it after any theme change and commit the diff.
"""

from __future__ import annotations

import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BINARY = ROOT / "build" / "pictura"
OUTPUT = ROOT / "design-system.html"


def dump_theme() -> dict:
    if not BINARY.exists():
        sys.exit(f"gen-styleguide: {BINARY} not found; build with `cmake --build build` first")
    result = subprocess.run(
        [str(BINARY), "--headless", "--dump-theme"],
        capture_output=True,
        text=True,
        check=True,
    )
    return json.loads(result.stdout)


def level_variables(levels: list[dict]) -> str:
    blocks = []
    for entry in sorted(levels, key=lambda level: level["level"]):
        lines = [f'[data-level="{entry["level"]}"] {{']
        for key in sorted(entry["colors"]):
            lines.append(f"  --{key}: {entry['colors'][key]};")
        lines.append("}")
        blocks.append("\n".join(lines))
    return "\n".join(blocks)


def metric_variables(metrics: dict) -> str:
    lines = [":root {"]
    for key in sorted(metrics):
        lines.append(f"  --{key}: {metrics[key]};")
    lines.append("}")
    return "\n".join(lines)


def token_table(levels: list[dict]) -> str:
    ordered = sorted(levels, key=lambda level: level["level"])
    keys = sorted(ordered[0]["colors"])
    head = "".join(f"<th>Level {level['level']}</th>" for level in ordered)
    rows = []
    for key in keys:
        cells = []
        for level in ordered:
            value = level["colors"][key]
            cells.append(
                f'<td><span class="chip" style="background:{value}"></span>'
                f"<code>--{key}</code><small>{value}</small></td>"
            )
        rows.append(f'<tr><th scope="row">--{key}</th>{"".join(cells)}</tr>')
    return (
        f'<table class="tokens"><thead><tr><th>Token</th>{head}</tr></thead>'
        f"<tbody>{''.join(rows)}</tbody></table>"
    )


def metrics_table(levels: list[dict]) -> str:
    ordered = sorted(levels, key=lambda level: level["level"])
    keys = sorted(ordered[0]["metrics"])
    head = "".join(f"<th>Level {level['level']}</th>" for level in ordered)
    rows = []
    for key in keys:
        cells = "".join(f"<td><code>{level['metrics'][key]}</code></td>" for level in ordered)
        rows.append(f'<tr><th scope="row">--{key}</th>{cells}</tr>')
    return (
        f'<table class="tokens"><thead><tr><th>Metric</th>{head}</tr></thead>'
        f"<tbody>{''.join(rows)}</tbody></table>"
    )


