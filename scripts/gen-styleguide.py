def build_html(dump: dict) -> str:
    levels = dump["levels"]
    default = dump["defaultLevel"]
    head = f"""<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Kooka Pictura design system</title>
<style>
{STYLE.replace("__METRICS__", metric_variables(levels[0]["metrics"])).replace("__LEVELS__", level_variables(levels))}
</style>
</head>
<body data-level="{default}">
<header>
  <h1>Kooka Pictura design system</h1>
  <p>Generated by <code>scripts/gen-styleguide.py</code> from
     <code>pictura --headless --dump-theme</code>. Every colour below comes from
     the theme token contract; Qt widgets and the global stylesheet are the
     implementation.</p>
  <div class="row">
    {"".join(
        f'<label><input type="radio" name="level" value="{level["level"]}"'
        f'{" checked" if level["level"] == default else ""}> Level {level["level"]}</label>'
        for level in sorted(levels, key=lambda entry: entry["level"])
    )}
  </div>
</header>
<h2>Colour tokens</h2>
{token_table(levels)}
<h2>Metrics</h2>
{metrics_table(levels)}
{PRIMITIVES}
{SCRIPT}
</body>
</html>
"""
    return head


def main() -> None:
    dump = dump_theme()
    html = build_html(dump)
    if OUTPUT.exists() and OUTPUT.read_text(encoding="utf-8") == html:
        print(f"gen-styleguide: {OUTPUT.name} unchanged")
        return
    OUTPUT.write_text(html, encoding="utf-8")
    print(f"gen-styleguide: wrote {OUTPUT.name}")


if __name__ == "__main__":
    main()
