#!/usr/bin/env python3
"""Regenerate Lens Correction's camera and lens catalogues.

Only factual columns are kept: names, crop factors, sensor sizes, a fixed
lens's range and aperture, and which corrections lensfun has calibrated. No
calibration coefficients and no images are copied.

Sources (download them yourself; see assets/PROVENANCE.md):
- cameras: leavestylecode/CameraDatabase `data/camera_data.csv` (MIT)
  https://github.com/leavestylecode/CameraDatabase
- lenses: the lensfun lens list page https://lensfun.github.io/lenslist/

Regenerate with:
  python3 scripts/gen-lens-catalog.py camera_data.csv lenslist.html
"""

from __future__ import annotations

import csv
import html
import re
import sys
from pathlib import Path

OUT = (
    Path(__file__).resolve().parent.parent
    / "crates/pictura-filters/src/distort/lens_correction"
)

CAMERA_HEADER = """\
# Camera bodies for Lens Correction's Search Criteria.
# Generated by scripts/gen-lens-catalog.py from leavestylecode/CameraDatabase
# data/camera_data.csv (MIT License, Copyright (c) 2025 leavestylecode);
# factual columns only. See assets/PROVENANCE.md.
# make\tmodel\tcrop\tsensor\tfixed-lens 35 mm range\tfixed-lens aperture
"""

LENS_HEADER = """\
# Lenses for Lens Correction's Search Criteria.
# Generated by scripts/gen-lens-catalog.py from the lensfun lens list
# (https://lensfun.github.io/lenslist/, the lensfun project); names, crop
# factors and which corrections lensfun calibrates only, no calibration
# data. See assets/PROVENANCE.md.
# make\tmodel\tcrop\tcalibrated (d distortion, t TCA, v vignetting)
"""


def clean(text: str) -> str:
    return " ".join(text.replace("\t", " ").split())


def number(text: str) -> str:
    try:
        return f"{float(text):g}"
    except ValueError:
        return ""


def cameras(path: Path) -> list[str]:
    rows = set()
    with path.open(encoding="utf-8", newline="") as f:
        for r in csv.DictReader(f):
            make, model = clean(r["Brand"]), clean(r["Model"])
            crop = number(r["Crop factor"].strip())
            if not make or not model or not crop:
                continue
            focal = re.sub(r"\s*-\s*", "-", r["Focal length (35mm equiv.)"])
            focal = clean(focal.replace("mm", ""))
            aperture = re.sub(r"\s*-\s*", "-", r["Max aperture"]).replace("f", "")
            rows.add(
                "\t".join([make, model, crop, clean(r["Sensor size"]), focal, clean(aperture)])
            )
    return sorted(rows, key=str.casefold)


ROW = re.compile(
    r'<tr class="lenslist-bg\d"><td>(.*?)</td><td>(.*?)</td><td>(.*?)</td>'
    r"<td[^>]*>(\w+)</td><td[^>]*>(\w+)</td><td[^>]*>(\w+)</td></tr>"
)


def lenses(path: Path) -> list[str]:
    text = path.read_text(encoding="utf-8")
    text = text[: text.find("<h2>Cameras")]
    rows = set()
    make = ""
    for m in ROW.finditer(text):
        if m.group(1):
            make = clean(html.unescape(m.group(1)))
        flags = "".join(
            code for code, value in zip("dtv", m.groups()[3:]) if value == "yes"
        )
        crop = number(m.group(3))
        model = clean(html.unescape(m.group(2)))
        if make and model and crop:
            rows.add("\t".join([make, model, crop, flags]))
    return sorted(rows, key=str.casefold)


def main() -> int:
    if len(sys.argv) != 3:
        print(__doc__, file=sys.stderr)
        return 2
    cams = cameras(Path(sys.argv[1]))
    lens = lenses(Path(sys.argv[2]))
    (OUT / "cameras.tsv").write_text(CAMERA_HEADER + "\n".join(cams) + "\n", encoding="utf-8")
    (OUT / "lenses.tsv").write_text(LENS_HEADER + "\n".join(lens) + "\n", encoding="utf-8")
    print(f"{len(cams)} cameras, {len(lens)} lenses")
    return 0


if __name__ == "__main__":
    sys.exit(main())
