#!/usr/bin/env python3
"""Regenerate the per-camera colour matrices vendor raw files use (#1465).

Each matrix is fitted from measured camera spectral sensitivities, not copied:
for a training set of reflectance spectra lit by a CIE illuminant, it is the
3 x 3 map from camera response to CIE 1931 XYZ that keeps the illuminant's
white exact and otherwise minimizes the squared XYZ error. The DNG-style
`ColorMatrix` (XYZ -> camera) is its inverse, scaled so the illuminant white
(Y = 1) has a largest camera component of 1. One matrix is fitted under CIE
illuminant A and one under D65, the pair the camera colour stage interpolates.

Sources (download them yourself; see assets/PROVENANCE.md):
- camera sensitivities, the 190-patch training spectra, the CIE 1931 colour
  matching functions and model aliases: AcademySoftwareFoundation/rawtoaces-data
  at commit e9b8503cf8a0641f40e5345d9757bde60c15f423 (Apache-2.0; the CMF file
  is the CIE's, CC-BY-4.0)
  https://github.com/AcademySoftwareFoundation/rawtoaces-data
- CIE standard illuminant D65, doi:10.25039/CIE.DS.hjfjmt59 (CC BY-SA 4.0)
  https://files.cie.co.at/Publications-datasets/CIE_std_illum_D65.csv
CIE illuminant A is computed from its Planckian definition.

Regenerate with:
  git clone https://github.com/AcademySoftwareFoundation/rawtoaces-data
  git -C rawtoaces-data checkout e9b8503cf8a0641f40e5345d9757bde60c15f423
  python3 scripts/gen-camera-matrices.py rawtoaces-data CIE_std_illum_D65.csv
"""

from __future__ import annotations

import json
import math
import sys
from pathlib import Path

OUT = (
    Path(__file__).resolve().parent.parent
    / "crates/pictura-codec/src/dng/camera_matrices.rs"
)

WAVELENGTHS = range(380, 781, 5)

# Bodies whose raw files the vendor readers open, by rawtoaces-data file stem.
# Canon bodies that write CR2 (the EOS R and later CR3 bodies wait for #399).
BODIES = [
    "Canon_Digital_Rebel_XTi",
    "Canon_EOS-1D_X_Mark_II",
    "Canon_EOS-1Ds_Mark_II",
    "Canon_EOS-1Ds_Mark_III",
    "Canon_EOS_100D",
    "Canon_EOS_200D",
    "Canon_EOS_5D",
    "Canon_EOS_5DS",
    "Canon_EOS_5D_Mark_II",
    "Canon_EOS_5D_Mark_III",
    "Canon_EOS_5D_Mark_IV",
    # Canon_EOS_600D waits: the CR2 reader misreads its CFA phase (#1476).
    "Canon_EOS_M",
    # Its alias the EOS 6D Mark II (same sensor) writes CR2.
    "Canon_EOS_RP",
    "Canon_PowerShot_S90",
]

HEADER = """\
//! Per-camera colour matrices for raw files that embed none (#1465).
//!
//! Generated by scripts/gen-camera-matrices.py; do not edit. Each matrix is
//! fitted from camera spectral sensitivities in AcademySoftwareFoundation/
//! rawtoaces-data (Apache-2.0) under CIE illuminants A and D65, with the CIE
//! 1931 observer. No Adobe or dcraw matrix is used. See assets/PROVENANCE.md.
//! `model` keys are normalized by `vendor::model_key`.

/// One camera's fitted XYZ → camera matrices, row-major.
pub(super) struct CameraMatrices {
    pub make: &'static str,
    pub models: &'static [&'static str],
    /// Under CIE illuminant A (EXIF `LightSource` 17).
    pub illuminant_a: [f64; 9],
    /// Under CIE D65 (EXIF `LightSource` 21).
    pub d65: [f64; 9],
}

#[rustfmt::skip]
pub(super) const CAMERAS: &[CameraMatrices] = &[
"""


def model_key(make: str, model: str) -> str:
    """Keep in step with `vendor::model_key` in the Rust reader."""
    words = model.upper().replace("-", " ").split()
    make_word = make_key(make)
    if words and words[0] == make_word:
        words = words[1:]
    return " ".join(w for w in words if w not in ("EOS", "DIGITAL"))


def make_key(make: str) -> str:
    words = make.upper().split()
    return words[0] if words else ""


def spectrum(data: dict, column: int | None = None) -> list:
    return [
        data[str(w)] if column is None else data[str(w)][column] for w in WAVELENGTHS
    ]


def load(path: Path) -> dict:
    return json.loads(path.read_text())["spectral_data"]["data"]["main"]


def illuminant_a() -> list:
    c2 = 1.435e7
    return [
        100.0
        * (560.0 / w) ** 5
        * (math.exp(c2 / (2848 * 560)) - 1)
        / (math.exp(c2 / (2848 * w)) - 1)
        for w in WAVELENGTHS
    ]


def illuminant_d65(path: Path) -> list:
    table = {}
    for line in path.read_text().splitlines():
        if line.strip():
            w, v = line.split(",")[:2]
            table[int(float(w))] = float(v)
    return [table[w] for w in WAVELENGTHS]


def integrate(weights: list, light: list, reflectance: list) -> float:
    return sum(a * b * c for a, b, c in zip(weights, light, reflectance))


def invert(m: list) -> list:
    a, b, c = m[0]
    d, e, f = m[1]
    g, h, i = m[2]
    det = a * (e * i - f * h) - b * (d * i - f * g) + c * (d * h - e * g)
    if abs(det) < 1e-12:
        raise ValueError("singular matrix")
    return [
        [(e * i - f * h) / det, (c * h - b * i) / det, (b * f - c * e) / det],
        [(f * g - d * i) / det, (a * i - c * g) / det, (c * d - a * f) / det],
        [(d * h - e * g) / det, (b * g - a * h) / det, (a * e - b * d) / det],
    ]


def mat_vec(m: list, v: list) -> list:
    return [sum(m[r][k] * v[k] for k in range(3)) for r in range(3)]


def fit_row(cams: list, targets: list, white_cam: list, white_target: float) -> list:
    """Least-squares `b` with `b . cam ~ target`, subject to `b . white_cam =
    white_target` (closed form via a Lagrange multiplier)."""
    gram = [[sum(c[i] * c[j] for c in cams) for j in range(3)] for i in range(3)]
    inv = invert(gram)
    rhs = [sum(c[i] * t for c, t in zip(cams, targets)) for i in range(3)]
    b0 = mat_vec(inv, rhs)
    g = mat_vec(inv, white_cam)
    lam = (white_target - sum(x * y for x, y in zip(b0, white_cam))) / sum(
        x * y for x, y in zip(g, white_cam)
    )
    return [x + lam * y for x, y in zip(b0, g)]


def lab(xyz: list, white: list) -> list:
    def f(t: float) -> float:
        return t ** (1 / 3) if t > (6 / 29) ** 3 else t / (3 * (6 / 29) ** 2) + 4 / 29

    fx, fy, fz = (f(v / w) for v, w in zip(xyz, white))
    return [116 * fy - 16, 500 * (fx - fy), 200 * (fy - fz)]


def fit(sens: list, cmf: list, patches: list, light: list) -> tuple:
    norm = integrate(cmf[1], light, [1.0] * len(light))
    white_xyz = [integrate(cmf[k], light, [1.0] * len(light)) / norm for k in range(3)]
    white_cam = [integrate(sens[k], light, [1.0] * len(light)) for k in range(3)]
    xyzs = [[integrate(cmf[k], light, p) / norm for k in range(3)] for p in patches]
    cams = [[integrate(sens[k], light, p) for k in range(3)] for p in patches]
    cam_to_xyz = [
        fit_row(cams, [x[k] for x in xyzs], white_cam, white_xyz[k]) for k in range(3)
    ]
    xyz_to_cam = invert(cam_to_xyz)
    peak = max(mat_vec(xyz_to_cam, white_xyz))
    matrix = [[v / peak for v in row] for row in xyz_to_cam]
    errors = []
    for c, x in zip(cams, xyzs):
        a, b = lab(mat_vec(cam_to_xyz, c), white_xyz), lab(x, white_xyz)
        errors.append(math.dist(a, b))
    return matrix, sum(errors) / len(errors), max(errors)


def rust_matrix(m: list) -> str:
    rows = "".join(
        "            " + ", ".join(f"{v:.6f}" for v in row) + ",\n" for row in m
    )
    return "[\n" + rows + "        ]"


def main() -> int:
    if len(sys.argv) != 3:
        print(__doc__, file=sys.stderr)
        return 2
    data = Path(sys.argv[1]) / "data"
    cmf_table = load(data / "cmf/cmf_1931.json")
    cmf = [spectrum(cmf_table, k) for k in range(3)]
    training = load(data / "training/training_spectral.json")
    patches = [[training[str(w)][i] for w in WAVELENGTHS] for i in range(190)]
    lights = {"A": illuminant_a(), "D65": illuminant_d65(Path(sys.argv[2]))}
    aliases = json.loads((data / "aliases.json").read_text())["data"]["camera"]["model"]

    out = [HEADER]
    for stem in BODIES:
        doc = json.loads((data / f"camera/{stem}_380_780_5.json").read_text())
        make, model = doc["header"]["manufacturer"], doc["header"]["model"]
        sens_table = doc["spectral_data"]["data"]["main"]
        sens = [spectrum(sens_table, k) for k in range(3)]
        keys = {model_key(make, model)}
        for alias, target in aliases.get(make, {}).items():
            if target["make"] == make and target["model"] == model:
                keys.add(model_key(make, alias))
        fitted = {}
        for name, light in lights.items():
            matrix, mean, worst = fit(sens, cmf, patches, light)
            fitted[name] = matrix
            print(
                f"{make} {model} {name}: training dE76 mean {mean:.2f} max {worst:.2f}",
                file=sys.stderr,
            )
        models = ", ".join(f'"{k}"' for k in sorted(keys))
        out.append(
            "    CameraMatrices {\n"
            f'        make: "{make_key(make)}",\n'
            f"        models: &[{models}],\n"
            f"        illuminant_a: {rust_matrix(fitted['A'])},\n"
            f"        d65: {rust_matrix(fitted['D65'])},\n"
            "    },\n"
        )
    out.append("];\n")
    OUT.write_text("".join(out))
    print(f"wrote {OUT}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
