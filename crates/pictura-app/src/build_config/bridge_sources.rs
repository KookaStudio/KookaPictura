//! The checked-in bridge-source list.
//!
//! `build.rs` may not discover the bridge set by watching `src/`: Cargo would
//! rerun the cxx-qt build script on every Rust edit, and the script cannot skip
//! its own work because `CxxQtBuilder::build` is what emits this crate's
//! `rustc-link-lib` for Qt and the `cxxqt_*` cfg. The list is therefore a
//! generated, checked-in file the build script reads and watches instead.
//!
//! The list is never hand-edited. Run the bridge-source tests with
//! `PICTURA_WRITE_BRIDGE_SOURCES=1` to rewrite it.

use std::path::Path;

use super::{bridge_files, read};

/// The list, at the crate root so `build.rs` can read it without a path guess.
const LIST: &str = include_str!("../../bridge_sources.txt");

const WRITE_ENV: &str = "PICTURA_WRITE_BRIDGE_SOURCES";

// Split for the same reason `build_config.rs` splits its copy: a literal marker
// would make this file read as a 75th bridge to the CMake configure scan.
const BRIDGE_MARKER: &str = concat!("cxx_qt", "::bridge");

fn parse(text: &str) -> Vec<String> {
    text.lines()
        .map(str::trim)
        .filter(|line| !line.is_empty() && !line.starts_with('#'))
        .map(str::to_owned)
        .collect()
}

/// The blessed path of each bridge, crate-relative and sorted.
pub(super) fn listed() -> Vec<String> {
    parse(LIST)
}

/// Rewrite the checked-in list when asked; returns whether it did.
fn bless() -> bool {
    if std::env::var(WRITE_ENV).as_deref() != Ok("1") {
        return false;
    }
    let paths = discovered();
    let mut out = String::from(
        "# Generated by the bridge-source tests; do not edit.\n\
         # Regenerate: PICTURA_WRITE_BRIDGE_SOURCES=1 cargo nextest run -p pictura-app bridge_sources\n",
    );
    for path in &paths {
        out.push_str(path);
        out.push('\n');
    }
    let target = Path::new(env!("CARGO_MANIFEST_DIR")).join("bridge_sources.txt");
    std::fs::write(&target, out).unwrap_or_else(|e| panic!("write {}: {e}", target.display()));
    let written = std::fs::read_to_string(&target)
        .unwrap_or_else(|e| panic!("read {}: {e}", target.display()));
    assert_eq!(
        parse(&written),
        paths,
        "bridge_sources.txt did not round-trip"
    );
    true
}

/// The bridges on disk, crate-relative with forward slashes, sorted.
pub(super) fn discovered() -> Vec<String> {
    bridge_files()
        .into_iter()
        .map(|path| {
            path.strip_prefix(env!("CARGO_MANIFEST_DIR"))
                .expect("a bridge outside the crate")
                .components()
                .map(|part| part.as_os_str().to_string_lossy())
                .collect::<Vec<_>>()
                .join("/")
        })
        .collect()
}

#[test]
fn bridge_sources_match_the_tree() {
    if bless() {
        return;
    }
    let expected = discovered();
    let actual = listed();
    let missing: Vec<&String> = expected.iter().filter(|p| !actual.contains(p)).collect();
    let stale: Vec<&String> = actual.iter().filter(|p| !expected.contains(p)).collect();
    assert!(
        missing.is_empty() && stale.is_empty(),
        "bridge_sources.txt differs from the tree\n\
         unlisted ({}): {missing:#?}\nstale ({}): {stale:#?}\n\
         regenerate with {WRITE_ENV}=1",
        missing.len(),
        stale.len()
    );
    assert_eq!(actual, expected, "bridge_sources.txt is not sorted");
}

#[test]
fn bridge_sources_are_all_real_bridges() {
    for entry in listed() {
        let path = Path::new(env!("CARGO_MANIFEST_DIR")).join(&entry);
        assert!(path.is_file(), "{entry} is listed but does not exist");
        let src = read(&path);
        assert!(
            src.contains(BRIDGE_MARKER),
            "{entry} is listed but carries no bridge module"
        );
    }
}
